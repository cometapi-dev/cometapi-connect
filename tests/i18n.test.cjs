const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '..', 'cometapi_helper', 'static');
const context = {globalThis: {}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'i18n.js'), 'utf8'), context);
const {chooseLocale, translate} = context.globalThis.CometI18n;
assert.equal(chooseLocale(['fr-CA', 'en-US']), 'fr');
assert.equal(chooseLocale(['xx', 'pt-BR']), 'pt');
assert.equal(chooseLocale(['zh-Hant-HK']), 'zh-TW');
assert.equal(chooseLocale(['zh-CN']), 'zh-TW');
assert.equal(chooseLocale(['ar-EG']), 'ar');
assert.equal(chooseLocale(['en-US'], 'ja'), 'ja');
assert.equal(chooseLocale(['ko-KR'], 'invalid'), 'ko');
assert.equal(chooseLocale(['xx']), 'en');
assert.equal(chooseLocale([]), 'en');
assert.equal(translate('Apps selected: {count}', {'Apps selected: {count}':'已選擇 {count} 個應用程式'}, {count:2}), '已選擇 2 個應用程式');
assert.equal(translate('Unknown diagnostic', {}), 'Unknown diagnostic');
assert.equal(translate('Value: {value}', {'Value: {value}':'值：{value}'}, {value:'<img onerror=alert(1)>'}), '值：<img onerror=alert(1)>');
console.log('Locale matching, preference override, fallback and interpolation passed.');
